"""Generate documentation that must not drift from the code: lineage diagram and data dictionary.

    python scripts/gen_docs.py            # reads data/gopulse.duckdb + pipelines/catalog/catalog.yml, writes docs/lineage.md, docs/data_dictionary.md

* Lineage is drawn from the `upstream` edges in the catalog (the same metadata the website's Data Catalog serves).
* The data dictionary reads real column names/types from the database and joins the curated descriptions.
"""
from __future__ import annotations

import argparse
from pathlib import Path

import duckdb
import yaml

CATALOG = Path("pipelines/catalog/catalog.yml")
SOURCES = {"bronze_events": "Bronze: accepted raw events", "raw_users": "Dimension snapshot: users", "raw_accounts": "Dimension snapshot: accounts",
           "raw_features": "Dimension snapshot: features", "stg_events": "dbt staging view"}
LAYER_STYLE = {"source": "#e2e8f0", "silver": "#cbd5e1", "gold": "#fde68a", "mart": "#bbf7d0"}


def lineage_mermaid(models: list[dict]) -> str:
    layer = {m["name"]: m["layer"] for m in models}
    for s in SOURCES:
        layer.setdefault(s, "source")
    lines = ["flowchart LR", "  subgraph SRC[\"Sources and Bronze\"]"]
    lines += [f"    {s}[\"{s}\"]" for s in SOURCES if s != "stg_events"]
    lines += ["  end"]
    for lyr, title in (("silver", "Silver"), ("gold", "Gold (PySpark/DuckDB)"), ("mart", "dbt marts")):
        lines.append(f"  subgraph {lyr.upper()}[\"{title}\"]")
        lines += [f"    {m['name']}[\"{m['name']}\"]" for m in models if m["layer"] == lyr]
        lines.append("  end")
    lines.append("  stg_events[\"stg_events (dbt view)\"]")
    seen = set()
    for m in models:
        for u in m.get("upstream", []):
            if (u, m["name"]) not in seen:
                seen.add((u, m["name"]))
                lines.append(f"  {u} --> {m['name']}")
    lines.append("  bronze_events --> silver_events")
    lines.append("  silver_events --> stg_events")
    for name, lyr in layer.items():
        lines.append(f"  style {name} fill:{LAYER_STYLE[lyr]},stroke:#475569,color:#0f172a")
    return "\n".join(lines)


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--db", type=Path, default=Path("data/gopulse.duckdb"))
    p.add_argument("--out", type=Path, default=Path("docs"))
    a = p.parse_args(argv)
    cfg = yaml.safe_load(CATALOG.read_text(encoding="utf-8"))
    models = cfg["models"]

    mermaid = lineage_mermaid(models)
    (a.out / "lineage.md").write_text(
        "# Data lineage\n\n"
        "Generated by `scripts/gen_docs.py` from `pipelines/catalog/catalog.yml` (the same metadata the Data Catalog page serves). "
        "Do not edit by hand.\n\n```mermaid\n" + mermaid + "\n```\n\n"
        "Colours: grey = sources/Silver, yellow = Gold, green = dbt marts.\n"
        "Gold is produced by `pipelines/jobs/gold.py` (DuckDB) and, in parity, `pipelines/spark/spark_pipeline.py` (PySpark/Delta); "
        "marts are dbt models that read Gold tables as dbt sources.\n", encoding="utf-8")

    con = duckdb.connect(str(a.db), read_only=True)
    out = ["# Data dictionary\n",
           ("Generated by `scripts/gen_docs.py` from the live DuckDB schema plus curated descriptions in `pipelines/catalog/catalog.yml`. "
            "Column types are the DuckDB types of the local implementation. All data is synthetic.\n"),
           f"{len(models)} models. Layers: Silver (cleaned events), Gold (dimensions, facts, aggregates), marts (dbt, rates with explicit denominators).\n"]
    for m in models:
        schema = "marts" if m["layer"] == "mart" else "main"
        cols = con.execute("SELECT column_name, data_type FROM information_schema.columns WHERE table_schema = ? AND table_name = ? "
                           "ORDER BY ordinal_position", [schema, m["name"]]).fetchall()
        n = con.execute(f'SELECT count(*) FROM {schema}."{m["name"]}"').fetchone()[0]
        desc = m.get("columns", {})
        out += [f"\n## `{m['name']}`  ·  {m['layer']}\n", f"{m['description']}  ", f"**Purpose:** {m.get('purpose', '-')}  ",
                f"**Grain:** {m['grain']}  ", f"**Primary key:** `{m['primary_key']}`  ",
                f"**Upstream:** {', '.join(f'`{u}`' for u in m.get('upstream', [])) or 'source data'}  ",
                f"**Source:** `{m['source']}`  ", f"**Rows in the demo dataset:** {n:,}\n",
                "| Column | Type | Description |", "|---|---|---|"]
        out += [f"| `{c}` | `{t}` | {desc.get(c, '')} |" for c, t in cols]
    (a.out / "data_dictionary.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {a.out / 'lineage.md'} and {a.out / 'data_dictionary.md'} ({len(models)} models)")


if __name__ == "__main__":
    main()
